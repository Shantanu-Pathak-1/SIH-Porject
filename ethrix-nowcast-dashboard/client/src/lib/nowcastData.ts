export interface BilingualAlert {
  hindi: string;
  english: string;
  urgency: "HIGH" | "CRITICAL" | "EXTREME";
  safeZones: string[];
  helpline: string;
  affectedCatchment: string;
}

export interface XaiFeatureAttribution {
  feature: string;
  source: string;
  weight: number; // percentage (0-100)
  value: string;
  anomalyScore: string;
  description: string;
}

export interface NowcastDistrict {
  id: DistrictId;
  name: string;
  state: string;
  catchment: string;
  coordinates: [number, number];
  elevationMeters: number;
  risk: RiskLevel;
  riskIndex: number;
  // Core Atmospheric & AI Metrics
  cape: number; // J/kg (Convective Available Potential Energy)
  cin: number; // J/kg (Convective Inhibition)
  cloudTopTemp: number; // °C (INSAT-3D TIR1 channel)
  radarReflectivity: number; // dBZ (IMD Doppler Radar)
  rainfallRate: number; // mm/h current instant intensity
  accumulatedRainfall: number; // mm (3-hour accumulation)
  soilSaturation: number; // %
  leadTime: string; // e.g. "2h 15m"
  threatCategory: "Cloudburst" | "Flash Flood" | "Severe Thunderstorm" | "Advisory";
  // Multi-Head U-Net Probabilities (Tier 2 Output)
  cloudburstProb: number; // %
  flashFloodProb: number; // %
  thunderstormProb: number; // %
  // Tier 3 Explainable AI (Grad-CAM)
  gradCamIntensity: number; // 0.0 - 1.0 (saliency heatmap weight)
  primaryTrigger: string;
  triggers: string[];
  xaiAttributions: XaiFeatureAttribution[];
  // Tier 4 GenAI Bilingual Alert
  bilingualAlert: BilingualAlert;
  // Backwards-compat aliases for existing UI tiles
  rainfall: number;
  saturation: number;
  station: string;
  sensorCount: string;
  action: string;
}

export interface GradCamZone {
  zoneId: string;
  name: string;
  center: [number, number];
  radiusMeters: number;
  intensity: number; // 0.0 to 1.0
  heatColor: string; // hex or rgba
  triggerSummary: string;
  leadTimeWindow: string;
}

export interface NowcastTimeStep {
  id: number;
  label: string;
  relativeTime: string; // e.g. "T - 3h 00m"
  timestamp: string; // e.g. "15:00 IST"
  phaseTitle: string;
  phaseSummary: string;
  radarCompositeDbz: number;
  insat3dMinCtt: number; // °C
  peakCape: number; // J/kg
  activeGradCamZones: GradCamZone[];
  districts: NowcastDistrict[];
}

